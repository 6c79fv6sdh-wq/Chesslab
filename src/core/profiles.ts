/**
 * Локальные профили без регистрации.
 *
 * Профиль — это просто имя, набранное руками, и выданный под него
 * `profileId`. Ни пароля, ни сервера: всё лежит в IndexedDB устройства.
 *
 * Важное свойство, ради которого это сделано именно так: список чужих
 * профилей нигде не показывается. Занятия идут на общем планшете, и
 * видеть, кто ещё на нём занимался, ученику незачем. Поэтому вход —
 * только набором своего имени: совпало с сохранённым — вошёл в свой
 * профиль со всеми данными, не совпало — предложение создать новый.
 * Функции ниже намеренно НЕ отдают наружу перечисление профилей;
 * `findProfileByName` возвращает ровно один профиль по точному совпадению.
 */

/** Профиль ученика на этом устройстве. */
export interface Profile {
  id: string;
  /** Имя как его набрали — с регистром и пробелами. */
  name: string;
  /** Ключ для поиска: имя, приведённое к сравнимому виду. */
  nameKey: string;
  createdAt: number;
  lastSeenAt: number;
}

export const NAME_MIN = 2;
export const NAME_MAX = 24;

/**
 * Ключ имени для поиска и проверки занятости.
 *
 * Регистр и лишние пробелы не должны мешать войти: «Ваня», «ваня» и
 * « Ваня » — один человек. Ещё приводим ё к е — на планшете её набирают
 * через раз, а промахнувшись, ученик увидел бы предложение завести
 * второй профиль вместо входа в свой.
 */
export function nameKeyOf(name: string): string {
  return name.trim().toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

export interface NameCheck {
  ok: boolean;
  /** Готовое сообщение для пользователя, если имя не годится. */
  error?: string;
  /** Имя после обрезки пробелов — его и надо сохранять. */
  clean: string;
}

/** Управляющие символы: почти всегда вставка из буфера, ломают вёрстку. */
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/;

export function validateName(raw: string): NameCheck {
  const clean = raw.trim().replace(/\s+/g, ' ');
  if (clean.length < NAME_MIN) {
    return { ok: false, clean, error: `Имя короче ${NAME_MIN} символов.` };
  }
  if (clean.length > NAME_MAX) {
    return { ok: false, clean, error: `Имя длиннее ${NAME_MAX} символов.` };
  }
  if (CONTROL_CHARS.test(clean)) {
    return { ok: false, clean, error: 'В имени есть недопустимые символы.' };
  }
  return { ok: true, clean };
}
