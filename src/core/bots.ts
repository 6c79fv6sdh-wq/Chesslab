/**
 * Сколько кандидатов сети вообще рассматриваем.
 *
 * Ограничение важнее, чем кажется: шестой по предпочтению ход Maia —
 * это уже не «так тоже играют», а редкая случайность. Держим выбор
 * в пределах правдоподобных человеческих ходов.
 */
export const MAX_CANDIDATES = 4;

/**
 * Выбор хода среди кандидатов сети по температуре.
 *
 * Считаем по МЕСТУ кандидата в списке, а не по его оценке. Так вышло не
 * из красоты, а по замеру: lc0 просят посчитать позицию в один узел
 * (`nodes 1`), и оценки всех кандидатов в этом режиме почти одинаковы —
 * сеть успевает оценить только корень. Softmax по таким оценкам
 * вырождается в равномерный выбор: на стенде e2e/strength.ts уже при
 * T=0.25 средняя потеря подскакивала со 96 до 263 сантипешек, а дальше
 * не росла и не падала — чистый шум вместо ручки громкости.
 *
 * Порядок кандидатов сеть при этом даёт осмысленный: первый — самый
 * вероятный ход человека, дальше по убыванию. По нему и работаем:
 *   вес(i) = exp(-i / T)
 * T → 0 — всегда первый (это «честная» Maia своего уровня);
 * чем больше T, тем чаще берутся второй и третий по популярности ходы.
 * Все они остаются ходами, которые люди в таких позициях реально
 * делают, — мы не подмешиваем случайные зевки, а лишь смещаем выбор
 * внутри человеческого распределения.
 */
export function sampleByTemperature(
  entries: { move: string; score: number }[],
  temperature: number,
  rnd: () => number,
  candidates = MAX_CANDIDATES,
): string | null {
  if (!entries.length) return null;
  const pool = entries.slice(0, Math.max(1, candidates));
  if (temperature <= 0) return pool[0].move;

  const weights = pool.map((_, i) => Math.exp(-i / temperature));
  const total = weights.reduce((a, b) => a + b, 0);
  if (!Number.isFinite(total) || total <= 0) return pool[0].move;

  let roll = rnd() * total;
  for (let i = 0; i < pool.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return pool[i].move;
  }
  return pool[pool.length - 1].move;
}
