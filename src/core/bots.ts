/**
 * Соперники для партий.
 *
 * Почему не «Stockfish послабее». UCI_Elo у Stockfish ослабляет движок,
 * подмешивая ошибки в оценку, но выбор хода остаётся машинным: движок
 * играет «правильно, только иногда мимо». Человек ошибается не так —
 * он не видит целые идеи, ставит фигуры туда, куда их «принято» ставить,
 * и зевает в узнаваемых местах. Отсюда постоянное ощущение, что даже
 * слабый Stockfish играет «не как человек, но всё равно обыгрывает».
 *
 * Maia — сеть, обученная предсказывать ход РЕАЛЬНОГО игрока данного
 * рейтинга по партиям Lichess. Её ход — это не «лучший ход с ошибкой»,
 * а самый вероятный человеческий ход в позиции. Поэтому здесь Maia
 * выбирает ход, а Stockfish используется отдельно — как оценщик
 * качества (для разбора и для проверки реальной силы), а не как игрок.
 *
 * Про два слабых бота. У Maia нет сети слабее 1100. «Ослаблять» её
 * случайными зевками нельзя — это ровно та беда, от которой уходим.
 * Вместо этого играем ТЕМПЕРАТУРОЙ: берём не самый вероятный ход сети,
 * а один из нескольких самых вероятных. Все кандидаты остаются ходами,
 * которые люди в таких позициях реально делают, — просто чаще берётся
 * не «типичный», а «тоже встречающийся» ход. Сама Maia отмечает, что её
 * сети сильнее своего номинала, потому что играют СРЕДНИЙ ход рейтинга;
 * такой выбор этот перекос как раз снимает.
 *
 * Замер (e2e/strength.ts, 6 партий по 46 полуходов, потеря считается
 * Stockfish на глубине 12). ACPL — средняя потеря в сантипешках,
 * «зевки» — доля ходов с потерей от 300 сп:
 *
 *   Щенок Пижон      ACPL 301   зевков 33,3 %  (10 партий, см. blind-bot.ts)
 *   Принцесса        ACPL 233   зевков 26,4 %  (10 партий, тот же прогон)
 *   Нейрофилософ     ACPL 178   зевков 15,3 %  (18 партий)
 *   Майкл            ACPL 168   зевков 15,3 %  (18 партий, тот же прогон)
 *   Наполеон         ACPL 161   зевков 14,9 %  (18 партий, тот же прогон)
 *   Сол              ACPL 130   зевков  8,8 %
 *   Кубрик           ACPL 105   зевков  4,5 %
 *   Лало             ACPL  73   зевков  0,0 %
 *
 * У Новичка/Майи 1000 числа отличаются от более ранних прогонов (было
 * 182/137) — обычный шум малой выборки, не считаются заново на каждый
 * коммит. Тройка выше — из ОДНОГО прогона, специально ради сравнения
 * между собой, этому можно доверять больше, чем абсолютным цифрам.
 *
 * У ботов на локальной эвристике (Щенок Пижон, Принцесса) числа от прогона к
 * прогону гуляют заметнее, чем у Maia — выборка небольшая, а решение
 * вероятностное на каждом ходу. Их числа выше — из одного и того
 * же прогона, для честного сравнения между собой.
 *
 * Здесь и видно исходную жалобу: у «движка 1400» зевков вдвое меньше,
 * чем у живого игрока того же рейтинга, а у 1800 их нет вовсе. Он не
 * «слабый соперник», он ровный — и потому обыгрывает даже там, где
 * человек того же номинала подарил бы фигуру. У Maia доля зевков
 * человеческая, поэтому с ней партия ощущается как партия с ровесником.
 *
 * Щенок Пижон и Принцесса (kind: 'blind') устроены принципиально иначе обоих
 * подходов выше — не сеть и не Elo-ограниченный движок, а имитация
 * тактической слепоты новичка 300–400/500 по ТЗ тренера с реальными
 * учениками. Принцесса на той же механике, что и Щенок Пижон, просто чаще
 * замечает найденную угрозу (BlindProfile.seeMaterialThreatChance и
 * парные) — не другая идея игры, а более внимательный ученик того же
 * типа. Подробно почему и как — в core/blind-bot.ts.
 */

import { BEGINNER_PROFILE, STUDENT_PROFILE, type BlindProfile } from './blind-bot';

export type BotEngineKind = 'maia' | 'stockfish' | 'simple' | 'blind';

export interface BotDef {
  id: string;
  name: string;
  /**
   * Слаг картинки: public/avatars/<avatar>.webp.
   *
   * Отдельное поле, а не id, специально. id заморожен — он лежит в
   * каждой сохранённой партии, и resumeGame() восстанавливает соперника
   * именно по нему (см. scramble.ts): переименуй id — и старые партии
   * молча доигрывались бы уже против другого бота. А имена файлов при
   * этом должны читаться по персонажу, а не по движку под ним, иначе
   * «Наполеон» лежал бы в maia-1000.webp.
   */
  avatar: string;
  /** Заявленный рейтинг. null — «максимум». */
  rating: number | null;
  kind: BotEngineKind;
  /** Файл весов в public/lc0 — только для maia. */
  net?: string;
  /**
   * Температура сэмплирования политики Maia.
   * 0 — всегда самый вероятный ход (это и есть «честная» Maia уровня).
   * >0 — чаще берутся менее типичные, но всё ещё человеческие ходы.
   */
  temperature?: number;
  /**
   * Сколько кандидатов сети рассматривать. Больше — глубже в хвост
   * человеческих ходов, то есть слабее. По умолчанию MAX_CANDIDATES.
   */
  candidates?: number;
  /** Для stockfish-ботов: значение UCI_Elo. null — полная сила. */
  elo?: number | null;
  /** Только для kind: 'blind' — параметры имитации новичка, см. blind-bot.ts. */
  blindProfile?: BlindProfile;
  /** Строка под кнопкой в интерфейсе. */
  note: string;
}

