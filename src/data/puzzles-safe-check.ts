import type { Role } from 'chessops/types';

/**
 * Задачи «безопасный шах»: шах, при котором шахующую фигуру нельзя взять.
 *
 * Позиции — из настоящих партий Lichess. Импортированы скриптом
 * tools/import-safe-checks.mjs, который заново проверяет каждую задачу
 * движком правил, а не полагается на метаданные исходного файла: ход
 * легален, даёт шах, это не мат, шахует именно сходившая фигура и она
 * одна, взять её нельзя (включая взятие на проходе), и такой ход в
 * позиции ровно один. Последнее важно: упражнение принимает единственный
 * ответ, и второй безопасный шах означал бы ошибку за верное решение.
 *
 * Те же проверки повторяет tests/puzzles-safe-check.test.ts, так что
 * битая задача не доедет до сборки.
 */
export interface SafeCheckPuzzle {
  /** Идентификатор внутри набора. */
  id: string;
  fen: string;
  /** Единственный безопасный шах в позиции. */
  uci: string;
  san: string;
  /** Чем шахуем — для разбора статистики по фигурам. */
  piece: Role;
  /** Есть ли в позиции шах-обманка, после которого фигуру бьют. */
  hasUnsafeAlternative: boolean;
  /** Партия-источник на Lichess: lichess.org/<id> */
  gameId: string;
}

